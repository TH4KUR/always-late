"""Judge the R5 cells with the rules fixed in reports/audit_our_vs_duan.md section 5 (stdlib only; run after fetching results).

  python3 scripts/g0/r5_compare.py --r5 reports/g0/r5 \
      --baseline reports/g0/baseline_full/<run>/phase3_summary_final.csv \
      --published third_party/duan2026/pristine/results/tables/phase3_summary_final.csv \
      [--r2 reports/g0/R2_bos_mask/<run>/phase3_summary_final.csv] --out reports/g0/r5/r5_report.md
"""
import argparse, csv
from pathlib import Path

MATERIAL_PP, MINOR_PP = 5.0, 1.0                       # single-factor materiality (identical re-runs of their code differ by <= 0.15 pp)
ANCHOR_PP, ANCHOR_MEDIAN, ANCHOR_PPL = 3.0, 0.01, 0.01  # T must reproduce the vendored baseline this closely
CROSS_PP = 3.0                                          # R2 (TL + masked BOS) vs T_mask (HF + masked BOS)
R2_BOS_PP = 10.0                                        # R2's own rule: BOS material if INT7 moves >= 10 pp from the baseline
EPS = 1e-9                                              # a difference of exactly the tolerance must pass despite float rounding (0.96 - 0.95 = 0.010000000000000009)
DEMO_DEFAULT = (98.28, 94.31)                           # our original 2,048-token demo, INT7 / INT6
REFERENCE = {"O_keep": "T_keep", "O_mask": "T_mask"}                        # comparator for a cell; default is T
NOTES = {"T": "attn eager, SAE fp32, their quantizer, no BOS (anchor)", "T_sdpa": "T with sdpa attention (no soft-cap)", "T_bf16sae": "T with bf16 SAE",
         "T_rowquant": "T with per-row q/k/v quantizer", "T_mask": "T + BOS, position 0 masked", "T_keep": "T + BOS kept",
         "O": "our pipeline (sdpa, bf16 SAE, per-row quantizer), no BOS", "O_keep": "our pipeline with BOS kept, on their tokens",
         "O_mask": "our pipeline with BOS prepended, position 0 masked"}


def _num(v):
    try:
        return float(v)
    except (TypeError, ValueError):
        return v


def load_summary(path):
    with open(path, newline="") as f:
        return {r["condition"]: {k: _num(v) for k, v in r.items()} for r in csv.DictReader(f)}


def find_cells(root, skip=("R5smoke",)):
    cells = {}
    for f in sorted(Path(root).rglob("phase3_summary_final.csv")):
        if not any(p in skip for p in f.parts):
            cells[f.parent.name] = load_summary(f)
    return cells


def surv(cell, bits):
    return cell[f"RTN INT{bits}"]["survived_>0.9_pct"]


def med(cell, bits):
    return cell[f"RTN INT{bits}"]["median_corr"]


def _within(diff, tol):
    return abs(diff) <= tol + EPS


def anchor_check(T, base):
    d = {}
    for b in (7, 6):
        d[f"INT{b}_survival_within_3pp"] = _within(surv(T, b) - surv(base, b), ANCHOR_PP)
        d[f"INT{b}_median_within_0.01"] = _within(med(T, b) - med(base, b), ANCHOR_MEDIAN)
    d["perplexity_within_1pct"] = _within(T["FP16 baseline"]["perplexity"] / base["FP16 baseline"]["perplexity"] - 1, ANCHOR_PPL)
    d["pass"] = all(d.values())
    return d


def classify(d7, d6):
    m = max(abs(d7), abs(d6)) + EPS
    return "material" if m >= MATERIAL_PP else "minor" if m >= MINOR_PP else "none"


def factor_deltas(cells):
    out = {}
    for name, c in cells.items():
        ref = cells.get(REFERENCE.get(name, "T"))
        if name == "T" or ref is None or name == REFERENCE.get(name):
            continue
        d7, d6 = surv(c, 7) - surv(ref, 7), surv(c, 6) - surv(ref, 6)
        out[name] = {"vs": REFERENCE.get(name, "T"), "INT7": d7, "INT6": d6, "class": classify(d7, d6)}
    return out


def additivity(cells):
    need = ("T", "T_sdpa", "T_bf16sae", "T_rowquant", "O")
    if any(n not in cells for n in need):
        return None
    res = {}
    for b in (7, 6):
        T = surv(cells["T"], b)
        res[f"INT{b}"] = {"sum_single": sum(surv(cells[n], b) - T for n in need[1:4]), "joint": surv(cells["O"], b) - T}
    return res


def loop_closure(o_keep, demo=DEMO_DEFAULT):
    return {"INT7": surv(o_keep, 7) - demo[0], "INT6": surv(o_keep, 6) - demo[1]}


def cross_stack(r2, t_mask):
    d = {f"INT{b}": surv(r2, b) - surv(t_mask, b) for b in (7, 6)}
    d.update({f"INT{b}_within_3pp": _within(d[f"INT{b}"], CROSS_PP) for b in (7, 6)})
    return d


def _row(name, c, note=""):
    return (f"| {name} | {surv(c, 8):.2f} | {surv(c, 7):.2f} | {surv(c, 6):.2f} | {med(c, 7):.4f} | {med(c, 6):.4f} | {c['FP16 baseline']['perplexity']:.1f} | "
            f"{c['RTN INT7']['perplexity'] / c['FP16 baseline']['perplexity'] * 100 - 100:+.2f} | {int(c['FP16 baseline']['n_active_features'])} | {note} |")


def render(cells, baseline, published, demo=DEMO_DEFAULT, r2=None):
    L = ["# R5 report (generated by scripts/g0/r5_compare.py; rules: reports/audit_our_vs_duan.md section 5)", "",
         "| cell | INT8 surv % | INT7 surv % | INT6 surv % | INT7 median r | INT6 median r | FP ppl | INT7 ppl % | active | note |", "|---|---|---|---|---|---|---|---|---|---|",
         _row("published (Duan)", published), _row("vendored baseline (job 23472)", baseline)]
    L += [_row(n, c, NOTES.get(n, "")) for n, c in cells.items()]
    if r2 is not None:
        L.append(_row("R2 (their TL code, BOS masked)", r2))
    L.append("")
    if "T" in cells:
        a = anchor_check(cells["T"], baseline)
        L += ["## Anchor: T vs the vendored baseline", "", f"**{'PASS' if a['pass'] else 'FAIL'}**: " + ", ".join(f"{k}={v}" for k, v in a.items() if k != "pass"), ""]
    fd = factor_deltas(cells)
    if fd:
        L += ["## Single-factor and joint deltas (survival, pp)", "", "| cell | vs | INT7 | INT6 | class |", "|---|---|---|---|---|"]
        L += [f"| {n} | {d['vs']} | {d['INT7']:+.2f} | {d['INT6']:+.2f} | {d['class']} |" for n, d in fd.items()] + [""]
    ad = additivity(cells)
    if ad:
        L += ["## Additivity (sum of single-factor deltas vs the joint cell O - T)", ""] + [f"- {k}: sum {v['sum_single']:+.2f} pp, joint {v['joint']:+.2f} pp" for k, v in ad.items()] + [""]
    if "O_keep" in cells:
        lc = loop_closure(cells["O_keep"], demo)
        L += [f"## Loop closure: O_keep vs our original demo ({demo[0]} / {demo[1]})", "", f"- INT7 {lc['INT7']:+.2f} pp, INT6 {lc['INT6']:+.2f} pp", ""]
    if r2 is not None:
        if "T_mask" in cells:
            cs = cross_stack(r2, cells["T_mask"])
            L += ["## Cross-stack: R2 vs T_mask", "", f"- INT7 {cs['INT7']:+.2f} pp (within 3 pp: {cs['INT7_within_3pp']}), INT6 {cs['INT6']:+.2f} pp (within 3 pp: {cs['INT6_within_3pp']})", ""]
        d7 = surv(r2, 7) - surv(baseline, 7)
        L += ["## R2's own rule", "", f"- INT7 survival moves {d7:+.2f} pp from the baseline ({'material' if abs(d7) >= R2_BOS_PP else 'not material'} at {R2_BOS_PP:.0f} pp)", ""]
    return "\n".join(L)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--r5", required=True); ap.add_argument("--baseline", required=True); ap.add_argument("--published", required=True)
    ap.add_argument("--r2"); ap.add_argument("--demo", default=",".join(map(str, DEMO_DEFAULT))); ap.add_argument("--out")
    a = ap.parse_args(argv)
    demo = tuple(float(x) for x in a.demo.split(","))
    md = render(find_cells(a.r5), load_summary(a.baseline), load_summary(a.published), demo, load_summary(a.r2) if a.r2 else None)
    if a.out:
        Path(a.out).write_text(md + "\n")
    print(md)


if __name__ == "__main__":
    main()
